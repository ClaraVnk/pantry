"""The names the schema *actually* carries in PostgreSQL, against the ones it declares.

Revision ``0010`` renamed eighteen check constraints across eight tables whose
names had landed in the database with their prefix doubled --
``ck_budget_target_ck_budget_target_amount_positive`` -- because revisions
``0005`` and ``0006`` declared a constraint as ``name="ck_budget_target_amount_
positive"`` when the naming template on ``Base.metadata`` is already
``ck_%(table_name)s_%(constraint_name)s``. The declared string is a *component*
of the final name, not the whole of it. Four of the eighteen went past
PostgreSQL's 63-character limit and were truncated by SQLAlchemy to a stem plus a
four-hex-digit hash, so their deployed names could not be derived by reading any
source file -- only by querying ``pg_constraint``.

Nothing in the repository could see it. The model reads correctly, the migrations
read correctly, and the tests were green: the divergence existed only in the
PostgreSQL catalogue, where it left every deployed constraint unaddressable by
name -- no ``IntegrityError`` handler can map a violated constraint to a message,
and no later revision can alter one without hardcoding a truncation hash.

Autogenerate does not close the hole, in either direction, and both halves of
that were measured against this schema rather than assumed:

* it does not compare check constraints at all, so a doubled ``ck`` name leaves
  ``alembic check`` perfectly clean -- all eighteen were invisible to it;
* where it *does* compare a name -- a unique constraint, an index -- it reports a
  ``remove_constraint`` followed by an identical-looking ``add_constraint``, on
  every run, and the diff it prints does not contain either name. The symptom is
  visible; the cause is not.

So this file compares the **catalogue to the model** -- not the migrations to the
model, and not autogenerate's opinion of either. That is the only comparison that
sees what truncation produced, because truncation happens when the DDL is
emitted, after every source file has had its say.

Two guards, and each one has a test that watches it fail:

* :func:`test_the_catalogue_matches_the_model` walks ``pg_constraint`` and
  ``pg_index`` on a database migrated to ``head`` and diffs the names against
  what ``Base.metadata`` renders. It catches a migration that drifted from the
  model, whatever the cause.
* :func:`test_declared_names_do_not_repeat_the_template_prefix` reads the model
  alone. It catches the doubling in the case the first guard cannot see -- the
  one where the *model* carries the doubled name too, so the database agrees with
  it and the diff is empty.

Both cover the five naming families (``ck``, ``uq``, ``fk``, ``pk``, ``ix``).
Only the ``ck`` template interpolates ``%(constraint_name)s`` today, so only
``ck`` can double; checking the other four costs a few lines and survives a
change to the convention, which
:func:`test_every_naming_family_is_covered` makes mandatory.
"""

