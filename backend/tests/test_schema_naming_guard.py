#: The PostgreSQL identifier preparer -- the object that decides what a name looks
#: like once it reaches the database, truncation included. Asking it rather than
#: reimplementing its rule is the whole reason this guard can tell a legitimate
#: truncation from a doubled prefix.
#:
#: ``Dialect.__init__`` carries no annotations, hence the ignore; the preparer it
#: returns is typed.
_PREPARER: Final = postgresql.dialect().identifier_preparer  # type: ignore[no-untyped-call]

_FAMILIES: Final[tuple[str, ...]] = ("pk", "fk", "uq", "ck", "ix")

_FAMILY_BY_CONSTRAINT_TYPE: Final[dict[type, str]] = {
    PrimaryKeyConstraint: "pk",
    ForeignKeyConstraint: "fk",
    UniqueConstraint: "uq",
    CheckConstraint: "ck",
}

#: ``pg_constraint.contype`` to naming family.
_FAMILY_BY_CONTYPE: Final[dict[str, str]] = {"p": "pk", "f": "fk", "u": "uq", "c": "ck"}

#: Floors on how many names a scan must find before its verdict is worth
#: anything. They are not an inventory of the schema: they sit at roughly half of
#: what it carries today, so ordinary growth never touches them.
#:
#: They exist because of the way this class of test fails silently. A scan that
#: finds nothing -- a catalogue query that lost its schema filter, a metadata
#: import that resolved to an empty ``Base`` -- produces an empty diff, and an
#: empty diff reads exactly like "no mismatch". The suite would then certify a
#: schema it never looked at. Lowering a floor is a deliberate edit, which is the
#: review conversation this constant exists to force.
_MINIMUM_NAMES_PER_FAMILY: Final[dict[str, int]] = {
    "pk": 15,
    "fk": 25,
    "uq": 5,
    "ck": 15,
    "ix": 15,
}

_MINIMUM_NAMES_TOTAL: Final = 100

#: ``backend/``, holding ``alembic.ini`` and ``migrations/``.
_BACKEND_ROOT: Final = Path(__file__).resolve().parent.parent


# --------------------------------------------------------------------------- #
# What a name is, on each side
# --------------------------------------------------------------------------- #


@dataclass(frozen=True, slots=True, order=True)
class SchemaName:
    """One constraint or index name, spelled as PostgreSQL stores it."""

    table: str
    family: str
    name: str

    def __str__(self) -> str:
        return f"{self.table}.{self.name} ({self.family})"


@dataclass(frozen=True, slots=True)
class DeclaredName:
    """What the model renders for one constraint or index, before and after truncation.

    ``full`` is what the naming template produces, of any length. ``stored`` is
    what PostgreSQL will actually hold: ``full``, truncated by the dialect when it
    exceeds 63 characters.

    **Legitimate truncation is not an offence, and this is where the two cases are
    kept apart.** SQLAlchemy truncates deterministically -- a stem plus the last
    four hex digits of the md5 of the full name -- and applies that same rule when
    a migration emits the DDL. Both sides therefore land on the same string, which
    is why the two foreign keys of ``recipe_suggestion_ingredient`` compare equal
    despite being cut short, and why the comparison below is made on ``stored``
    rather than on ``full``. A doubled prefix, in contrast, produces a *different*
    string on each side and still fails.

    Do not "simplify" this by comparing ``full`` on both sides: ``full`` is a
    property of the model only, so that would compare the model with itself and
    the guard would pass on every database ever built.
    """

    table: str
    family: str
    full: str
    stored: str

    @property
    def key(self) -> SchemaName:
        return SchemaName(self.table, self.family, self.stored)


def _render(name: str, family: str) -> str:
    """Apply the dialect's truncation rule to a convention-rendered name."""
    label = conv(name)
    if family == "ix":
        return _PREPARER.truncate_and_render_index_name(label, _alembic_quote=False)
    return _PREPARER.truncate_and_render_constraint_name(label, _alembic_quote=False)


def _declared_names(metadata: MetaData) -> tuple[DeclaredName, ...]:
    """Every constraint and index name the metadata renders, in both spellings.

    Nothing here can come out unnamed. A check constraint declared without a
    ``name=`` raises at import time -- the ``ck`` template interpolates
    ``%(constraint_name)s`` and SQLAlchemy refuses to render it from nothing --
    and the other four templates build a name out of the table and its columns.
    The assertions below are therefore a statement of that fact, not a branch
    anyone is expected to reach.
    """
    collected: list[DeclaredName] = []
    for table in metadata.sorted_tables:
        for constraint in table.constraints:
            family = _FAMILY_BY_CONSTRAINT_TYPE.get(type(constraint))
            if family is None:  # pragma: no cover - no other constraint type is used
                continue
            assert constraint.name is not None, f"{table.name}: unnamed {family} constraint"
            full = str(constraint.name)
            collected.append(DeclaredName(table.name, family, full, _render(full, family)))
        for index in table.indexes:
            assert index.name is not None, f"{table.name}: unnamed index"
            full = str(index.name)
            collected.append(DeclaredName(table.name, "ix", full, _render(full, "ix")))
    return tuple(collected)


_MODEL_NAMES: Final[tuple[DeclaredName, ...]] = _declared_names(Base.metadata)
_MODEL_TABLES: Final[frozenset[str]] = frozenset(Base.metadata.tables)


# --------------------------------------------------------------------------- #
# The catalogue
# --------------------------------------------------------------------------- #

# `contype` is cast to text because asyncpg hands back PostgreSQL's `"char"` type
# as raw bytes, which compares equal to nothing.
_CATALOGUE_CONSTRAINTS: Final = text("""
    SELECT t.relname AS table_name, c.conname AS name, c.contype::text AS contype
    FROM pg_constraint AS c
    JOIN pg_class AS t ON t.oid = c.conrelid
    JOIN pg_namespace AS n ON n.oid = t.relnamespace
    WHERE n.nspname = current_schema()
      AND t.relkind = 'r'
      AND c.contype IN ('p', 'f', 'u', 'c')
""")

# Indexes that back a primary key or a unique constraint are already counted as
# constraints above; listing them again would report every one of them twice.
_CATALOGUE_INDEXES: Final = text("""
    SELECT t.relname AS table_name, i.relname AS name
    FROM pg_index AS x
    JOIN pg_class AS i ON i.oid = x.indexrelid
    JOIN pg_class AS t ON t.oid = x.indrelid
    JOIN pg_namespace AS n ON n.oid = i.relnamespace
    WHERE n.nspname = current_schema()
      AND t.relkind = 'r'
      AND NOT EXISTS (SELECT 1 FROM pg_constraint AS c WHERE c.conindid = i.oid)
""")


async def _catalogue_names(session: AsyncSession) -> frozenset[SchemaName]:
    """What PostgreSQL holds, restricted to the tables the model declares.

    ``alembic_version`` is Alembic's own bookkeeping and is not part of the model,
    so it is filtered out here rather than exempted by name further down.
    """
    collected: set[SchemaName] = set()
    for row in (await session.execute(_CATALOGUE_CONSTRAINTS)).all():
        if row.table_name in _MODEL_TABLES:
            collected.add(SchemaName(row.table_name, _FAMILY_BY_CONTYPE[row.contype], row.name))
    for row in (await session.execute(_CATALOGUE_INDEXES)).all():
        if row.table_name in _MODEL_TABLES:
            collected.add(SchemaName(row.table_name, "ix", row.name))
    return frozenset(collected)


# --------------------------------------------------------------------------- #
# The two detectors
# --------------------------------------------------------------------------- #

_WHY: Final = (
    "The naming template already adds the {prefix!r} prefix, so it must not appear in "
    "the name you declare: `ck` renders as {template!r}, which makes the declared string "
    "a *component* of the final name rather than the whole of it."
)


def _doubled_form(entry: SchemaName) -> SchemaName:
    """The name a declaration lands on when it repeats the template's prefix.

    A check constraint meant to be ``ck_budget_target_amount_positive``, declared
    as ``name="ck_budget_target_amount_positive"`` instead of
    ``name="amount_positive"``, reaches PostgreSQL as
    ``ck_budget_target_ck_budget_target_amount_positive`` -- truncated here by the
    same preparer that truncated it on the way in, so the four names that went
    past 63 characters are recognised too, hash and all.
    """
    doubled = f"{entry.family}_{entry.table}_{entry.name}"
    return SchemaName(entry.table, entry.family, _render(doubled, entry.family))


def _describe_mismatches(
    catalogue: frozenset[SchemaName], declared: Iterable[DeclaredName]
) -> list[str]:
    """One actionable line per name the database and the model disagree on."""
    expected = {entry.key for entry in declared}
    only_in_database = sorted(catalogue - expected)
    only_in_model = sorted(expected - catalogue)

    # Pair an unexpected database name with the model name it would have come from,
    # had the declaration repeated the template's prefix. This is what turns
    # "ck_shelf_life_guideline_ck_shelf_life_guideline_duratio_eb80" -- a string
    # derivable from no source file -- back into a diagnosis.
    origin_of: dict[SchemaName, SchemaName] = {
        _doubled_form(entry): entry for entry in only_in_model
    }

    lines: list[str] = []
    for entry in only_in_database:
        origin = origin_of.get(entry)
        prefix = f"{entry.family}_{entry.table}_"
        if origin is None:
            lines.append(
                f"{entry.table}: the database holds {entry.name!r} ({entry.family}) and the "
                f"model declares no such name. Either declare it in domain/models.py, or "
                f"drop it in a migration -- a constraint the model cannot name is a "
                f"constraint nothing in the application can address."
            )
            continue
        component = origin.name.removeprefix(prefix)
        lines.append(
            f"{entry.table}: the database holds {entry.name!r} where the model renders "
            f"{origin.name!r}. "
            + _WHY.format(prefix=prefix, template=NAMING_CONVENTION[entry.family])
            + f" Declare name={component!r}. Renaming an already-deployed constraint takes "
            f'a migration of its own -- `ALTER TABLE "{entry.table}" RENAME CONSTRAINT '
            f'"{entry.name}" TO "{origin.name}"`, as revision 0010 does.'
        )

    for entry in only_in_model:
        if _doubled_form(entry) in catalogue:
            continue  # already reported above, from the database's side
        prefix = f"{entry.family}_{entry.table}_"
        line = (
            f"{entry.table}: the model renders {entry.name!r} ({entry.family}) and the "
            f"database has no constraint or index by that name. A migration is missing, or "
            f"the one that created it used a name of its own."
        )
        # The mirror image of the case above: here it is the *model* that carries the
        # doubled name, and the database that holds the sane one.
        if entry.name.startswith(prefix * 2):
            line += (
                " "
                + _WHY.format(prefix=prefix, template=NAMING_CONVENTION[entry.family])
                + f" Declare name={entry.name[len(prefix) * 2 :]!r}."
            )
        lines.append(line)
    return lines


def _prefix_doublings(declared: Iterable[DeclaredName]) -> list[str]:
    """Declared names that already carried the prefix their template adds.

    Read from the model alone, so it fires before the mistake is ever migrated --
    and it fires in the one case :func:`_describe_mismatches` is blind to, where
    the model carries the doubled name as well and the database dutifully agrees.
    """
    offenders: list[str] = []
    for entry in declared:
        prefix = f"{entry.family}_{entry.table}_"
        if not entry.full.startswith(prefix * 2):
            continue
        offenders.append(
            f"{entry.table}: the {entry.family} name renders as {entry.full!r}. "
            + _WHY.format(prefix=prefix, template=NAMING_CONVENTION[entry.family])
            + f" Declare name={entry.full[len(prefix) * 2 :]!r} and the template will make it "
            f"{entry.full[len(prefix) :]!r}."
        )
    return offenders


def _assert_scan_is_plausible(names: Iterable[SchemaName], source: str) -> None:
    """Refuse to draw a conclusion from a scan that plainly read nothing.

    Raises ``AssertionError`` -- it is called from the tests it protects, and its
    failure must be their failure.
    """
    found = list(names)
    counts = {family: sum(1 for entry in found if entry.family == family) for family in _FAMILIES}
    assert len(found) >= _MINIMUM_NAMES_TOTAL, (
        f"the {source} scan found only {len(found)} names ({counts}), which is fewer than "
        f"{_MINIMUM_NAMES_TOTAL}. Nothing below this line is trustworthy: an empty scan "
        f"produces an empty diff, and an empty diff reads exactly like agreement. Fix the "
        f"scan, or lower _MINIMUM_NAMES_TOTAL on purpose if the schema really shrank."
    )
    short = {
        family: counts[family]
        for family, minimum in _MINIMUM_NAMES_PER_FAMILY.items()
        if counts[family] < minimum
    }
    assert not short, (
        f"the {source} scan found too few names in {short} (floors: "
        f"{_MINIMUM_NAMES_PER_FAMILY}). A family that collects nothing is a family this "
        f"guard silently stops covering."
    )


