def test_every_naming_family_is_covered() -> None:
    """A sixth template must not slip past this file unnoticed."""
    assert set(NAMING_CONVENTION) == set(_FAMILIES), (
        f"NAMING_CONVENTION declares {sorted(NAMING_CONVENTION)} and this guard covers "
        f"{sorted(_FAMILIES)}. Extend _FAMILIES, _FAMILY_BY_CONSTRAINT_TYPE, "
        f"_FAMILY_BY_CONTYPE and _MINIMUM_NAMES_PER_FAMILY, so the new family is compared "
        f"against the catalogue like the others."
    )


def test_the_model_scan_is_not_empty() -> None:
    """The floor, asserted on its own so a broken scan is reported as a broken scan."""
    _assert_scan_is_plausible((entry.key for entry in _MODEL_NAMES), source="model")


def test_declared_names_do_not_repeat_the_template_prefix() -> None:
    _assert_scan_is_plausible((entry.key for entry in _MODEL_NAMES), source="model")
    offenders = _prefix_doublings(_MODEL_NAMES)
    assert not offenders, "\n".join(["doubled name prefixes in the model:", *offenders])


async def test_the_catalogue_matches_the_model(db_session: AsyncSession) -> None:
    """Every name PostgreSQL holds is a name the model renders, and the reverse.

    The migrations are not read here. They are the thing under suspicion: each one
    of them was correct on its own terms, and the schema still drifted.
    """
    catalogue = await _catalogue_names(db_session)
    _assert_scan_is_plausible(catalogue, source="catalogue")
    _assert_scan_is_plausible((entry.key for entry in _MODEL_NAMES), source="model")

    mismatches = _describe_mismatches(catalogue, _MODEL_NAMES)
    assert not mismatches, "\n".join(
        ["the deployed schema and domain/models.py disagree on these names:", *mismatches]
    )


def test_the_migrations_leave_nothing_for_autogenerate_to_propose(
    initialised_database: str,
) -> None:
    """``alembic check`` on a database at ``head``: the drift this file does *not* cover.

    A backstop, not the guard. It was measured, not assumed: doubling a ``ck`` name
    in the model leaves this test green, because autogenerate never compares check
    constraints -- which is precisely why the guards above read ``pg_constraint``
    themselves. What it does catch is everything else that makes the model and the
    migrations describe different schemas: a forgotten column, a widened numeric, a
    renamed unique constraint or index. Cheap here, since the database is already
    migrated, and it is the command a developer would run by hand after editing the
    model.

    **Its second blind spot is computed columns**, and it announces it: this test is
    the source of the suite's only warning, *"Computed default on
    product.allergens_risk cannot be modified"*. Autogenerate skips generation
    expressions, so an edit to the ``CASE`` that decides whether a product is
    withheld from someone allergic to it would leave this green. That gap is covered
    by ``test_the_generated_column_still_computes_what_the_model_declares`` below,
    which compares the deployed expression against the model's declaration through
    PostgreSQL's own normaliser -- and by its companion, which proves the comparison
    can tell a changed expression from an unchanged one.

    Its diff is not actionable on its own. A renamed unique constraint is reported
    as a ``remove_constraint``/``add_constraint`` pair that prints columns and no
    names at all, which is why the failure message sends the reader upwards.

    Synchronous on purpose: ``migrations/env.py`` calls ``asyncio.run`` itself, so
    an ``async def`` test here would fail with "cannot be called from a running
    event loop" and say nothing about the schema.
    """
    # `Config()` with no file, options set by hand, rather than `Config(alembic.ini)`.
    # `migrations/env.py` calls `fileConfig(config.config_file_name)` whenever there
    # is one, and `fileConfig` disables every logger the file does not name --
    # `alembic.ini` names root, sqlalchemy and alembic, so `chaudron.seed` and the
    # rest come out of this call silenced for the remainder of the process. Three
    # tests in `test_seed_guard.py` then read an empty `caplog` and fail somewhere
    # else entirely. A test must not reconfigure the logging of the run it is part
    # of; leaving `config_file_name` at `None` is the whole fix, and the two options
    # below are all `check` needs from that file.
    config = Config()
    config.set_main_option("script_location", str(_BACKEND_ROOT / "migrations"))
    config.set_main_option("sqlalchemy.url", initialised_database)
    try:
        command.check(config)
    except AutogenerateDiffsDetected as detected:
        pytest.fail(
            f"`alembic check` is not clean against a database at head: {detected}. The model "
            f"and the migrations describe different schemas -- write the missing revision. "
            f"If the difference is a constraint *name*, read "
            f"test_the_catalogue_matches_the_model above before writing anything."
        )


