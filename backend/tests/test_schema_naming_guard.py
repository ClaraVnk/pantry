def test_the_plausibility_floor_rejects_an_empty_scan() -> None:
    """The guard that keeps the guard from passing on nothing.

    A census test that reads an empty collection concludes that every member of it
    is compliant. This suite has been bitten by exactly that shape once already --
    a route inventory that enumerated zero routes and certified them all
    authenticated -- so the floor gets a test of its own rather than trust.
    """
    with pytest.raises(AssertionError, match="found only 0 names"):
        _assert_scan_is_plausible([], source="deliberately empty")

    one_family_missing = [entry.key for entry in _MODEL_NAMES if entry.family != "ck"]
    with pytest.raises(AssertionError, match="too few names"):
        _assert_scan_is_plausible(one_family_missing, source="deliberately partial")


def test_the_model_guard_fails_on_a_doubled_name() -> None:
    """Build the mistake and watch the detector catch it.

    A throwaway ``MetaData`` carrying the project's own naming convention, and a
    check constraint declared the way revisions ``0005`` and ``0006`` declared
    theirs. Nothing here touches ``Base.metadata``.
    """
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    Table(
        "naming_guard_probe",
        metadata,
        Column("id", Integer, primary_key=True),
        Column("amount", Numeric(12, 2), nullable=False),
        # The mistake, verbatim: the prefix the template adds, typed by hand into
        # the name the template is given.
        CheckConstraint("amount > 0", name="ck_naming_guard_probe_amount_positive"),
    )

    declared = _declared_names(metadata)
    doubled = next(entry for entry in declared if entry.family == "ck")
    assert doubled.full == "ck_naming_guard_probe_ck_naming_guard_probe_amount_positive", (
        "the convention no longer doubles a pre-prefixed name; if that is deliberate, this "
        "whole file is about a mistake that can no longer be made"
    )

    offenders = _prefix_doublings(declared)
    assert len(offenders) == 1
    assert "ck_naming_guard_probe_ck_naming_guard_probe_amount_positive" in offenders[0]
    assert "already adds the 'ck_naming_guard_probe_' prefix" in offenders[0]
    assert "Declare name='amount_positive'" in offenders[0]

    # And the healthy declaration is not reported.
    assert not _prefix_doublings(entry for entry in declared if entry.family != "ck"), (
        "a name that does not repeat its prefix must never be reported"
    )


#: The four names that went past 63 characters, ``(table, intended, deployed)``,
#: as revision ``0010`` read them out of ``pg_constraint`` on a database migrated
#: to ``0009``. Observations, not configuration: they were not transcribed from
#: any source file, because no source file contains them.
_HISTORICAL_TRUNCATIONS: Final[tuple[tuple[str, str, str], ...]] = (
    (
        "infant_food_restriction",
        "ck_infant_food_restriction_bands_present",
        "ck_infant_food_restriction_ck_infant_food_restriction_b_df82",
    ),
    (
        "infant_food_restriction",
        "ck_infant_food_restriction_matcher_present",
        "ck_infant_food_restriction_ck_infant_food_restriction_m_21e9",
    ),
    (
        "recipe_suggestion",
        "ck_recipe_suggestion_feedback_matches_status",
        "ck_recipe_suggestion_ck_recipe_suggestion_feedback_matc_96f3",
    ),
    (
        "shelf_life_guideline",
        "ck_shelf_life_guideline_durations_positive",
        "ck_shelf_life_guideline_ck_shelf_life_guideline_duratio_eb80",
    ),
)


@pytest.mark.parametrize(
    ("table", "intended", "deployed"),
    _HISTORICAL_TRUNCATIONS,
    ids=[intended for _, intended, _deployed in _HISTORICAL_TRUNCATIONS],
)
def test_the_diagnosis_reproduces_the_names_that_were_actually_deployed(
    table: str, intended: str, deployed: str
) -> None:
    """The truncated four, the ones no reader could have derived, paired back by hand.

    This is what makes the failure message worth reading rather than merely true.
    ``_doubled_form`` has to reproduce SQLAlchemy's truncation exactly -- the stem
    cut at 55 characters plus an underscore and four hex digits of an md5 taken
    over the *full* name -- or a doubled long name would be reported as two
    unrelated strings ("the database has this, the model has that") and the reader
    would be back to querying the catalogue to work out which is which.

    Measured against the real deployment, so a future SQLAlchemy that changes its
    truncation rule fails here, loudly, instead of quietly degrading the diagnosis.
    """
    assert _doubled_form(SchemaName(table, "ck", intended)).name == deployed


async def test_the_catalogue_guard_fails_on_a_doubled_name(db_session: AsyncSession) -> None:
    """Reproduce the deployed bug on a real constraint, and watch the diff catch it.

    PostgreSQL rolls DDL back like anything else and ``db_session`` rolls back, so
    the rename lives for the length of this test and leaves the session's database
    exactly as it found it.

    The victim is chosen from the model rather than hardcoded: naming this file's
    proof after one particular constraint would make it fail the day that
    constraint is legitimately renamed, and a guard that fails for the wrong reason
    gets deleted.
    """
    victim = min(entry.key for entry in _MODEL_NAMES if entry.family == "ck")
    doubled = _doubled_form(victim)

    before = await _catalogue_names(db_session)
    assert victim in before, f"{victim} is not in the catalogue; the probe would prove nothing"
    assert not _describe_mismatches(before, _MODEL_NAMES), "the schema is already mismatched"

    # Identifiers are quoted rather than interpolated bare: they come from the
    # model's own metadata, so there is nothing to inject, and quoting is the form
    # that keeps working if a name ever needs it.
    await db_session.execute(
        text(f'ALTER TABLE "{victim.table}" RENAME CONSTRAINT "{victim.name}" TO "{doubled.name}"')
    )

    after = await _catalogue_names(db_session)
    assert doubled in after
    mismatches = _describe_mismatches(after, _MODEL_NAMES)

    assert len(mismatches) == 1, f"expected exactly one offence, got {mismatches}"
    report = mismatches[0]
    assert doubled.name in report, "the failure must name what is in the database"
    assert victim.name in report, "the failure must name what the model expects"
    assert f"already adds the 'ck_{victim.table}_' prefix" in report, (
        "the failure must say *why*, or the next reader has to reconstruct this file"
    )
    assert "RENAME CONSTRAINT" in report, "the failure must say how to repair a deployed database"


async def test_the_generated_column_still_computes_what_the_model_declares(
    db_session: AsyncSession,
) -> None:
    """The one drift ``alembic check`` above cannot see, and the riskiest to miss.

    Autogenerate refuses to compare computed defaults -- it says so out loud, as the
    suite's only warning: *"Computed default on product.allergens_risk cannot be
    modified"*. So the backstop that catches a forgotten column or a widened numeric
    is blind to the expression behind the single column that decides whether a
    product is withheld from someone who is allergic to it. A migration editing that
    ``CASE`` would leave every test in this file green.

    Comparing the two as *text* would be a test that fails on whitespace: PostgreSQL
    stores its own normalised rendering of the expression, not the string it was
    given. So the model's declaration is handed to PostgreSQL on a throwaway table
    and read back through the same normaliser. Both sides come out in the server's
    spelling, and what is left to compare is the meaning.

    ``tests/domain/test_allergen_unknown_is_not_safe.py`` covers the *behaviour* --
    that an undocumented product carries all fourteen allergens and is excluded by
    the obvious query. This covers the narrower thing that survives a subtler edit:
    that the deployed expression is still the declared one, including the branch a
    behavioural test might not happen to exercise.
    """
    deployed = await db_session.scalar(
        text(
            "SELECT generation_expression FROM information_schema.columns"
            " WHERE table_name = 'product' AND column_name = 'allergens_risk'"
        )
    )
    assert deployed, "product.allergens_risk is no longer a generated column"

    # Same expression, same server, same normaliser -- on a table that disappears
    # with this transaction's rollback.
    await db_session.execute(
        text(
            "CREATE TABLE _drift_probe ("
            " allergen_state allergen_data_state NOT NULL DEFAULT 'unknown',"
            " allergens_contains allergen[] NOT NULL DEFAULT '{}',"
            " allergens_may_contain allergen[] NOT NULL DEFAULT '{}',"
            f" allergens_risk allergen[] GENERATED ALWAYS AS ({_ALLERGENS_RISK_SQL}) STORED"
            ")"
        )
    )
    declared = await db_session.scalar(
        text(
            "SELECT generation_expression FROM information_schema.columns"
            " WHERE table_name = '_drift_probe' AND column_name = 'allergens_risk'"
        )
    )

    assert deployed == declared, (
        "product.allergens_risk no longer computes what domain/models.py declares.\n"
        f"deployed: {deployed}\ndeclared: {declared}\n"
        "`alembic check` cannot see this: it skips computed defaults. If the change "
        "is deliberate, write the revision that applies it to `product` too."
    )


async def test_the_generated_column_guard_notices_a_changed_expression(
    db_session: AsyncSession,
) -> None:
    """Build the drift and watch the detector catch it.

    A comparison of two strings the server produced could pass by being vacuous --
    both ``None``, or both normalised into the same thing regardless of input. The
    mutation here is the plausible one rather than an absurd one: dropping
    ``allergens_may_contain`` from the declared branch, which is how "may contain
    traces" quietly stops counting as a risk while every row still looks populated.
    """
    honest = _ALLERGENS_RISK_SQL
    drifted = honest.replace(" || allergens_may_contain", "")
    assert drifted != honest, "the mutation did not change the expression"

    await db_session.execute(
        text(
            "CREATE TABLE _drift_probe_mutated ("
            " allergen_state allergen_data_state NOT NULL DEFAULT 'unknown',"
            " allergens_contains allergen[] NOT NULL DEFAULT '{}',"
            " allergens_may_contain allergen[] NOT NULL DEFAULT '{}',"
            f" allergens_risk allergen[] GENERATED ALWAYS AS ({drifted}) STORED"
            ")"
        )
    )
    mutated = await db_session.scalar(
        text(
            "SELECT generation_expression FROM information_schema.columns"
            " WHERE table_name = '_drift_probe_mutated' AND column_name = 'allergens_risk'"
        )
    )
    deployed = await db_session.scalar(
        text(
            "SELECT generation_expression FROM information_schema.columns"
            " WHERE table_name = 'product' AND column_name = 'allergens_risk'"
        )
    )

    assert mutated, "the probe table did not produce a generation expression"
    assert mutated != deployed, (
        "the guard above cannot tell a changed expression from the deployed one, "
        "so its passing says nothing"
    )
